// Bundles ../public into src/static.generated.js so the Worker serves the UI
// itself (no separate static-asset upload step).
import fs from 'node:fs';
import path from 'node:path';

const dir = new URL('../public/', import.meta.url);
const types = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.svg': 'image/svg+xml', '.ico': 'image/x-icon' };
const files = {};
for (const name of fs.readdirSync(dir)) {
  const ext = path.extname(name);
  if (!types[ext]) continue;
  files[`/${name}`] = { type: types[ext], body: fs.readFileSync(new URL(name, dir), 'utf8') };
}
files['/'] = files['/index.html'];
fs.writeFileSync(new URL('./src/static.generated.js', import.meta.url),
  `// Generated by build-assets.mjs. Do not edit.\nexport default ${JSON.stringify(files)};\n`);
console.log(`bundled ${Object.keys(files).length - 1} files`);
